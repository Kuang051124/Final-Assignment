    c = v( sw_half,  hd, z_mid)
    d = v(-sw_half,  hd, z_mid)
    e = v(-sw_half,  hd - sd_half, z_top)
    f_ = v( sw_half,  hd - sd_half, z_top)
    g = v( sw_half,  hd, z_top)
    h_ = v(-sw_half,  hd, z_top)
    quad_floor(a, d, c, b)
    quad_floor(c, d, h_, g)
    quad_floor(d, a, e, h_)
    quad_floor(a, b, f_, e)
    quad_floor(e, f_, g, h_)

    # Slot inner walls (visible from above)
    # Front bridge inner wall
    a = v(-sw_half, -hd + sd_half, z_mid)
    b = v( sw_half, -hd + sd_half, z_mid)
    e_ = v(-sw_half, -hd + sd_half, z_top)
    f_ = v( sw_half, -hd + sd_half, z_top)
    quad_floor(b, a, e_, f_)

    # Back bridge inner wall
    a = v(-sw_half, hd - sd_half, z_mid)
    b = v( sw_half, hd - sd_half, z_mid)
    e_ = v(-sw_half, hd - sd_half, z_top)
    f_ = v( sw_half, hd - sd_half, z_top)
    quad_floor(a, b, f_, e_)

    # Slot floor
    a = v(-sw_half, -hd + sd_half, z_mid)
    b = v( sw_half, -hd + sd_half, z_mid)
    c = v( sw_half,  hd - sd_half, z_mid)
    d = v(-sw_half,  hd - sd_half, z_mid)
    quad_floor(a, b, c, d)

    write_obj(filepath, np.array(verts), np.array(norms), np.array(faces), color)


